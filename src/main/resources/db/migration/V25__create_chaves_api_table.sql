-- Incremento 79: chaves de API pra integrações (ver docs/chaves-api-plano.md, decisões
-- D1–D10 em docs/decisoes.md). A chave age em nome de um usuário vinculado (usuario_id),
-- que dá o perfil e aparece na auditoria. O segredo NUNCA é gravado — só o hash SHA-256
-- (hex, 64 caracteres), único e usado pra busca na autenticação; prefixo é só o rótulo
-- exibido na tela pra reconhecer a chave.
CREATE TABLE chaves_api (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    prefixo VARCHAR(20) NOT NULL,
    hash VARCHAR(64) NOT NULL UNIQUE,
    criada_em TIMESTAMP NOT NULL,
    criada_por_usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    -- Data (não instante): a chave vale até o fim desse dia, no fuso de São Paulo. NULL = não expira (D4).
    expira_em DATE,
    ultimo_uso_em TIMESTAMP,
    revogada_em TIMESTAMP,
    revogada_por_usuario_id BIGINT REFERENCES usuarios(id)
);

CREATE INDEX idx_chaves_api_usuario_id ON chaves_api (usuario_id);
